def scope_lock_guidance(stem: str) -> str:
    """源限定作答口径(轮次21,负证据题治理):检索已锁定某文档族时追加的
    system 指令。raglite(消息组装处)与 react(build_messages_node)共用,
    保证两路口径一致。stem 可含 "||" 联合锁定(近全等并列组,如同型号的
    手册+设备介绍),渲染为《a》《b》并列。"""
    names = [s for s in (stem or "").split("||") if s.strip()]
    ref = "".join(f"《{n.strip()}》" for n in names) or "《该资料》"
    return (
        f"【源限定】本次检索已限定于资料{ref}:\n"
        f"- 答案只能引用{ref}的内容,关键事实后标注该资料的来源;\n"
        f"- 若以上检索块未覆盖所问事实,必须明确回答\"{ref}未涉及所问内容\","
        "并简述该资料实际覆盖的相关范围(依据检索块内容);\n"
        f"- 严禁引用其他资料、外部知识或通用常识补充事实——即使其他资料里有"
        "看似相关的内容,也不是用户所指的资料,引用即为答非所问。"
    )

